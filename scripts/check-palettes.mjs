import assert from 'node:assert/strict';
import { paletteFor } from '../src/palettes.js';
import { installPresentation } from '../src/presentation.js';
import { createDemoProject,validateProject } from '../src/studio/project.js';
const nodes=new Map(),values=new Map(),styles=new Map();
const $=id=>{if(!nodes.has(id))nodes.set(id,{value:'',textContent:'',listeners:{},addEventListener(type,fn){this.listeners[type]=fn;},setAttribute(){}});return nodes.get(id);};
globalThis.localStorage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value)};
globalThis.document={documentElement:{dataset:{},style:{setProperty:(key,value)=>styles.set(key,value)}},addEventListener(){}};
globalThis.matchMedia=()=>({matches:false,addEventListener(){}});
const presentation=installPresentation({$,getTheater:()=>null,setTheater(){}});
presentation.setPalette('seminar');
assert.equal(styles.get('--bg'),'#faf9f5');assert.equal(styles.get('--ink'),'#141413');
assert.equal(styles.get('--orange'),'#c6613f');assert.equal(values.get('field-palette'),'seminar');
presentation.setTheme('dark');assert.equal(styles.get('--bg'),'#141413');assert.equal(styles.get('--ink'),'#faf9f5');
assert.equal(styles.get('--orange'),'#d97757');
assert.equal(paletteFor('seminar','light').blue,'#6a9bcc');
const demo=createDemoProject();demo.settings.palette='seminar';
assert.equal(validateProject(JSON.parse(JSON.stringify(demo))).settings.palette,'seminar');
delete demo.settings.palette;assert.equal(validateProject(demo).settings.palette,'default');
demo.settings.palette='bad';assert.throws(()=>validateProject(demo));
presentation.setPalette('default');assert.equal(styles.get('--bg'),paletteFor('default','dark').bg);
$('palette').value='seminar';$('palette').listeners.change({target:$('palette')});assert.equal(presentation.getPalette(),'seminar');
console.log('Passed: Typst palette colors, light/dark switching, selector, persistence, project round trip, legacy default and validation.');
